"""Render the curated home page (Top 20 + the two 'ten names' panels) from tools/home.json + data.json
into index.html, between the <!-- HOME:START --> and <!-- HOME:END --> markers. Static HTML: no JS needed."""
import json, re
from html import escape as e
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
data = {d['id']: d for d in json.loads((ROOT / 'data.json').read_text())['incidents']}
home = json.loads((ROOT / 'tools/home.json').read_text())
path = lambda d: d.get('slug') or d['id']

def picture(d):
    """the item's own preview image: share image, else its Commons image, else its poster figure"""
    if d.get('share'):
        return d['share'], ''
    if d.get('image'):
        im = d['image']
        return im['src'], f'{im.get("credit", "")} · {im.get("license", "")}'.strip(' ·')
    if d.get('figure'):
        return d['figure']['src'], ''
    return None, ''

def card(n, t):
    d = data[t['id']]
    src, credit = picture(d)
    url = f'/{path(d)}/'
    media = (f'<img src="{e(src)}" alt="" loading="{"eager" if n <= 3 else "lazy"}" decoding="async">' if src
             else f'<span class="t20-type" aria-hidden="true">{e(t["when"])}</span>')
    return f'''<article class="t20{'' if src else ' noimg'}" id="top-{e(d['id'])}">
  <div class="t20-media">{media}<span class="t20-n">{n:02d}</span>{f'<span class="t20-credit">{e(credit)}</span>' if credit else ''}</div>
  <div class="t20-body">
    <div class="t20-when">{e(t['when'])}</div>
    <h3><a href="{url}">{e(t['short'])}</a></h3>
    <p>{e(t['line'])}</p>
    {f'<p class="t20-off"><span>Official line</span>{e(t["official"])}</p>' if t.get('official') else ''}
    <a class="t20-more" href="{url}" aria-label="Full record: {e(t['short'])}">Full record · {len(d['links'])} sources →</a>
  </div>
</article>'''

def person(i, p, side):
    docket = data.get(p.get('id', ''))
    name = f'<a href="/{path(docket)}/">{e(p["name"])}</a>' if docket else e(p['name'])
    line = p.get('basis') or p.get('death')
    return (f'<li><span class="tn-i">{i:02d}</span><div><div class="tn-name">{name}</div><div class="tn-role">{e(p["role"])}</div>'
            f'<p>{e(line)} <a class="tn-src" href="{e(p["source"]["url"])}" target="_blank" rel="noopener">{e(p["source"]["label"])} ↗</a></p></div></li>')

def panel(key, cls):
    s = home[key]
    return (f'<section class="tn {cls}" aria-labelledby="tn-{key}"><h3 id="tn-{key}">{e(s["title"])}</h3><p class="tn-lede">{e(s["lede"])}</p>'
            f'<ol>{"".join(person(i + 1, p, key) for i, p in enumerate(s["people"]))}</ol></section>')

html = f'''<!-- HOME:START (generated by tools/home.py from tools/home.json — edit those, not this) -->
<section class="hero" id="top">
  <div class="hero-in">
    <div class="overline">Planetary Council · Gaza &amp; the West Bank · 2023–2026</div>
    <h1>The War Crimes Safari</h1>
    <p class="hero-sub">The most-documented record of war crimes we can build: one sentence each, every claim sourced, every official excuse on file.</p>
    <nav class="hero-cta"><a href="#top20">The Top 20</a><a href="#ten-names">Ten names, two sides</a><a href="#full-record">The full record ↓</a></nav>
    <p class="hero-counts" id="counts"></p>
  </div>
</section>
<section class="home-sec" id="top20">
  <h2>The Top 20</h2>
  <p class="sub">Twenty of the gravest, best-evidenced entries, in date order. Each card is one sentence; the full page behind it carries every source, dated and named.</p>
  <div class="t20-grid">
{chr(10).join(card(n + 1, t) for n, t in enumerate(home['top20']))}
  </div>
</section>
<section class="home-sec" id="ten-names">
  <h2>Ten names, two sides</h2>
  <p class="sub">The same question asked of both: who could be brought before a court of law?</p>
  <div class="tn-wrap">{panel('israel', 'il')}{panel('hamas', 'hm')}</div>
</section>
<!-- HOME:END -->'''

idx = ROOT / 'index.html'
t = idx.read_text()
t2 = re.sub(r'<!-- HOME:START.*?<!-- HOME:END -->', lambda m: html, t, flags=re.S)
if t2 == t and 'HOME:START' not in t:
    raise SystemExit('index.html has no HOME markers')
idx.write_text(t2)
print('home: rendered', len(home['top20']), 'cards')
